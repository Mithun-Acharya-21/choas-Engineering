export function generateInitialTelemetrySeries(): TelemetryPoint[] {
  const points: TelemetryPoint[] = [];
  const baseTime = new Date('2026-11-18T13:18:00Z').getTime();

  for (let i = 0; i < 36; i++) {
    const ts = new Date(baseTime + i * 30 * 1000);
    const label = ts.toISOString().substring(11, 19);
    const inFaultWindow = i >= 24;
    const wave = Math.sin(i * 0.45) * 4 + Math.cos(i * 0.22) * 3;
    const baselineP99 = Number((64 + wave).toFixed(1));
    const p50 = Number((16 + wave * 0.35 + (inFaultWindow ? 9.5 : 0)).toFixed(1));
    const p95 = Number((38 + wave * 0.65 + (inFaultWindow ? 94.0 : 0)).toFixed(1));
    const p99 = Number(
      (baselineP99 + (inFaultWindow ? 195 + Math.sin(i * 0.8) * 38 : Math.random() * 4)).toFixed(1)
    );
    const rps = Math.round(14750 + Math.sin(i * 0.3) * 420 - (inFaultWindow ? 380 : 0));
    const errorRate = Number((inFaultWindow ? 0.68 + Math.abs(Math.sin(i)) * 0.35 : 0.04 + (i % 3) * 0.01).toFixed(2));

    points.push({
      timestamp: label,
      p50,
      p95,
      p99,
      baselineP99,
      rps,
      errorRate,
      faultActive: inFaultWindow,
    });
  }
  return points;
}

export function buildTraceSpans(service: string, isCritical: boolean, totalMs: number): TraceSpan[] {
  const gatewayMs = Math.max(4, Math.round(totalMs * 0.08));
  const authMs = Math.max(6, Math.round(totalMs * 0.12));
  const checkoutMs = Math.max(12, Math.round(totalMs * 0.35));
  const downstreamMs = Math.max(8, totalMs - gatewayMs - authMs);

  const spans: TraceSpan[] = [
    {
      id: 'sp-01',
      service: 'api-gateway',
      operation: 'HTTP POST /v2/checkout/confirm',
      startOffsetMs: 0,
      durationMs: totalMs,
      status: isCritical ? 'error' : 'ok',
      tags: { 'http.method': 'POST', 'http.status': isCritical ? '503' : '200', namespace: 'sandbox-ingress' },
    },
    {
      id: 'sp-02',
      service: 'auth-service',
      operation: 'grpc.Auth/VerifySessionToken',
      startOffsetMs: gatewayMs,
      durationMs: authMs,
      status: 'ok',
      tags: { 'rpc.system': 'grpc', 'cache.hit': 'true', namespace: 'sandbox-identity' },
    },
    {
      id: 'sp-03',
      service: service === 'auth-service' ? 'inventory-cache' : 'checkout-core',
      operation: 'grpc.Checkout/ReserveAndSettle',
      startOffsetMs: gatewayMs + authMs,
      durationMs: Math.min(checkoutMs + 40, downstreamMs),
      status: totalMs > 180 ? 'degraded' : 'ok',
      tags: { 'chaos.fault': totalMs > 180 ? 'toxiproxy-delay-250ms' : 'none', pod: 'checkout-core-7f9b2', namespace: 'sandbox-checkout' },
    },
    {
      id: 'sp-04',
      service: 'payment-ledger',
      operation: 'sql.Tx/CommitSettlement',
      startOffsetMs: gatewayMs + authMs + Math.round(checkoutMs * 0.4),
      durationMs: Math.max(10, downstreamMs - Math.round(checkoutMs * 0.4)),
      status: isCritical ? 'error' : totalMs > 150 ? 'degraded' : 'ok',
      tags: { 'db.system': 'postgresql', 'retry.attempt': isCritical ? '3/3' : '0', namespace: 'sandbox-payments' },
    },
  ];
  return spans;
}

